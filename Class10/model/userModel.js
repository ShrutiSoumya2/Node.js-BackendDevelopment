import mongoose from "mongoose";

const userSchema = new mongoose.Schema({    //data stored in document format, key value pair in mongoose
    name: {
        type: String,
        require: true
    },
    age: {
        type: Number
    },
    gender: {
        type: String
    },
    course: {
        type: String
    }

})

const User = mongoose.model('User', userSchema)  //user is the name of collection, userSchema is the schema we created

export default User 


















































































































































































































































































